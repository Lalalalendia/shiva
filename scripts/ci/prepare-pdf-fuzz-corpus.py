#!/usr/bin/env python3
"""Prepare immutable PDF seeds and tiny semantic mutation instructions for libFuzzer.

Input directories have already passed the SHA-pinned CC0 and deterministic
ReportLab generators. Never write downloaded PDFs to source-controlled files.
"""
import argparse
import hashlib
from pathlib import Path
import sys

MAX_FILE = 256 * 1024
SOURCES = (
    ("SHIVA_QA_PINNED_PDF_DIR", "sample-1-page.pdf"),
    ("SHIVA_QA_PINNED_PDF_DIR", "sample-10-pages.pdf"),
    ("SHIVA_QA_PINNED_PDF_DIR", "sample-100-pages.pdf"),
    ("SHIVA_QA_REPORTLAB_DIR", "reportlab-12-pages.pdf"),
    ("SHIVA_QA_REPORTLAB_DIR", "reportlab-rotated-3-pages.pdf"),
)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--pdf-lib", required=True, type=Path)
    parser.add_argument("--reportlab", required=True, type=Path)
    parser.add_argument("--corpus", required=True, type=Path)
    args = parser.parse_args()
    root = args.corpus.resolve()
    expected_root = (Path.cwd() / "fuzz" / "corpus").resolve()
    if root != expected_root:
        raise ValueError("fuzz corpus must be confined to repository fuzz/corpus")
    if root.exists():
        raise ValueError("fuzz corpus already exists: not replacing previous inputs")
    root.mkdir(parents=True, mode=0o700)
    raw_dir = root / "pdf_parse"
    semantic_dir = root / "pdf_required_graph"
    raw_dir.mkdir(mode=0o700)
    semantic_dir.mkdir(mode=0o700)

    count = 0
    for source, basename in SOURCES:
        directory = args.pdf_lib if source == "SHIVA_QA_PINNED_PDF_DIR" else args.reportlab
        file = directory / basename
        if not file.is_file() or file.is_symlink():
            raise ValueError("missing or symlinked PDF fixture")
        data = file.read_bytes()
        if not (100 <= len(data) <= MAX_FILE) or not data.startswith(b"%PDF-"):
            raise ValueError("fuzzer PDF seed invalid or oversized")
        (raw_dir / basename).write_bytes(data)
        print(
            "SHIVA_FUZZ_PINNED_SEED=" + basename
            + ";bytes=" + str(len(data))
            + ";sha256=" + hashlib.sha256(data).hexdigest(),
            flush=True,
        )
        count += 1

    # Include direct graph-key and /Count digit mutations over every source.
    # Additional coverage-guided mutations are generated by libFuzzer.
    for source in range(4):
        for key in range(9):
            for variant in range(2):
                data = bytes((source, key, variant, variant))
                name = f"seed-{source:02}-{key:02}-{variant}"
                (semantic_dir / name).write_bytes(data)
    print(
        f"SHIVA_FUZZ_SEEDS=pass;pdfs={count};semantic={4 * 9 * 2}",
        flush=True,
    )


if __name__ == "__main__":
    try:
        main()
    except Exception as exc:
        print("SHIVA_FUZZ_SEEDS=fail;type=" + type(exc).__name__, file=sys.stderr)
        raise SystemExit(1)
